"""Generate docs/RESULTS.md and the README headline block from results/*.json (no number is typed by hand)."""

import json
from pathlib import Path

R = Path("results")


def load(name: str) -> dict:
    return json.loads((R / name).read_text())


def row(name: str, m: dict) -> str:
    return (
        f"| {name} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f']:.3f} [{m['f1_lo']:.3f}, {m['f1_hi']:.3f}] "
        f"| {m['f2']:.3f} | {m['specificity']:.3f} |"
    )


HEAD = "| system | precision | recall | F1 [95% CI] | F2 | specificity |\n|---|---|---|---|---|---|"
SYSTEMS = [
    "all-candidates",
    "B0 (VETR)",
    "B0 minus empty-box clauses",
    "B1 rules",
    "model noisy_or q>=0.5",
    "model noisy_or q>=0.7",
]
out = ["# Results (generated by scripts/make_results_md.py from results/*.json; do not edit by hand)\n"]
test = load("ledger_eval_test_majority_binding.json")
out.append("## Frozen test set, primary gold (majority of three annotators, binding set)\n")
out.append(HEAD)
for s in SYSTEMS:
    if s in test:
        out.append(row(s, test[s]))
rep = load("test_report.json")
out.append("\n### Pre-registered hypotheses\n")
out.append("| id | claim | outcome |\n|---|---|---|")
h1, h2, h3, h4 = rep["H1"], rep["H2"], rep["H3"], rep["H4"]
out.append(
    f"| H1 | {h1['claim']} | {'holds' if h1['holds'] else 'FAILS'}: {h1['diff']:+.3f} [{h1['ci'][0]:+.3f}, {h1['ci'][1]:+.3f}] |"
)
out.append(
    f"| H2 | {h2['claim']} | {'holds' if h2['holds'] else 'FAILS'}: specificity {h2['model_specificity']:.3f}, recall {h2['model_recall']:.3f}, B0 specificity {h2['b0_specificity']:.3f} |"
)
out.append(
    f"| H3 | {h3['claim']} | non-inferior: {h3['non_inferior']}; superior: {h3['superior']} ({h3['diff']:+.3f} [{h3['ci'][0]:+.3f}, {h3['ci'][1]:+.3f}]) |"
)
out.append(
    f"| H4 | {h4['claim']} | {'holds' if h4['holds'] else 'FAILS'}: coverage {h4['test_coverage']:.3f}, accuracy {h4['test_accuracy']:.3f} at t={h4['t_from_dev']:.3f} |"
)
rep2 = load("test_report_test_v2.json")
t2 = load("ledger_eval_test_v2_majority_binding.json")
out.append("\n## Corrected judges (post-hoc, D-031): label-letter collision removed, same frozen model\n")
out.append(HEAD)
for s_ in SYSTEMS:
    if s_ in t2:
        out.append(row(s_, t2[s_]))
g1, g2, g3, g4 = rep2["H1"], rep2["H2"], rep2["H3"], rep2["H4"]
out.append("\n| id | outcome on the corrected gold |\n|---|---|")
out.append(
    f"| H1 | {'holds' if g1['holds'] else 'FAILS'}: {g1['diff']:+.3f} [{g1['ci'][0]:+.3f}, {g1['ci'][1]:+.3f}] |"
)
out.append(
    f"| H2 | {'holds' if g2['holds'] else 'FAILS'}: specificity {g2['model_specificity']:.3f}, recall {g2['model_recall']:.3f}, B0 specificity {g2['b0_specificity']:.3f} |"
)
out.append(
    f"| H3 | non-inferior: {g3['non_inferior']}; lower bound {g3['ci'][0]:+.5f} (superiority not claimed, see D-031) |"
)
out.append(
    f"| H4 | {'holds' if g4['holds'] else 'FAILS'}: coverage {g4['test_coverage']:.3f}, accuracy {g4['test_accuracy']:.3f} |"
)
out.append(
    "\n## The same predictions against each single annotator and the applicable set (model q>=0.5 vs B0, F1 difference)\n"
)
out.append("| gold | n labelled (binding) | B0 F1 | model F1 | difference [95% CI] |\n|---|---|---|---|---|")
for tag, label in [
    ("test_agent", "agent only"),
    ("test_judge_gpt-4o-mini", "gpt-4o-mini only"),
    ("test_judge_gpt-4.1-mini", "gpt-4.1-mini only"),
    ("test_majority_binding", "majority, binding set"),
    ("test_majority_applicable_applicable", "majority, applicable set (B or R)"),
]:
    d = load(f"ledger_eval_{tag}.json")
    p = d["paired model noisy_or q>=0.5 vs B0 (VETR)"]
    out.append(
        f"| {label} | {d['_meta']['labelled']} ({d['_meta']['binding']}) | {d['B0 (VETR)']['f']:.3f} | {d['model noisy_or q>=0.5']['f']:.3f} | {p['diff']:+.3f} [{p['lo']:+.3f}, {p['hi']:+.3f}] |"
    )
obj = load("corpus_objective_overcount.json")
out.append("\n## Objective over-count by the status quo (no model, no annotator)\n")
out.append(
    f"Of {obj['b0_entries']:,} status-quo ledger entries, **{obj['b0_entries_only_in_empty_checklist_boxes']:,} ({obj['share_of_b0']:.1%})** are clause numbers whose every mention is a checklist item with an empty box; "
    f"{obj['documents_where_b0_counts_unchecked_items']} of {obj['documents_with_a_decided_checklist']} documents with a decided checklist are affected (median {obj['median_unchecked_per_affected_document']:.0f} per affected document). Lower bound."
)
vc = load("version_currency.json")
pre = vc["pre_rfo"]
c = pre["by_category"]
dated = pre["dated_entries"]
out.append("\n## Version currency (pre-RFO notices, eCFR is the authority)\n")
out.append(
    f"{dated:,} ledger entries cite a date: {c['matches_in_force']:,} ({c['matches_in_force'] / dated:.1%}) match the version in force on the posting day, {c['older_than_in_force']:,} ({c['older_than_in_force'] / dated:.1%}) cite an older version, {c['newer_than_in_force']:,} ({c['newer_than_in_force'] / dated:.1%}) a newer one; {c['no_date_cited']:,} entries have no attachable date."
)
Path("docs/RESULTS.md").write_text("\n".join(out) + "\n")

head = (
    f"- Frozen test (32 documents, {test['_meta']['labelled']} labelled numbers, LLM annotators), as pre-registered: F1 {test['model noisy_or q>=0.5']['f']:.3f} for the model vs {test['B0 (VETR)']['f']:.3f} for the status-quo regexes "
    f"(difference {h3['diff']:+.3f}, interval [{h3['ci'][0]:+.3f}, {h3['ci'][1]:+.3f}]: non-inferior, **not shown better**); specificity {test['model noisy_or q>=0.5']['specificity']:.0%} vs {test['B0 (VETR)']['specificity']:.0%}.\n"
    f"- After correcting a label-letter collision in the judge protocol (post-hoc, D-031): F1 {t2['model noisy_or q>=0.5']['f']:.3f} vs {t2['B0 (VETR)']['f']:.3f} (lower bound {g3['ci'][0]:+.5f}, so no superiority claim), specificity {t2['model noisy_or q>=0.5']['specificity']:.0%} vs {t2['B0 (VETR)']['specificity']:.0%}; H2 {'holds' if g2['holds'] else 'fails'} on the corrected gold.\n"
    f"- Objective, annotator-free: **{obj['share_of_b0']:.1%}** of status-quo ledger entries are clauses whose own checklist box is empty ({obj['documents_where_b0_counts_unchecked_items']} of {obj['documents_with_a_decided_checklist']} documents with a decided checklist).\n"
    f"- Pre-registered hypotheses as originally scored: H1 {'holds' if h1['holds'] else 'fails'}, H2 {'holds' if h2['holds'] else 'FAILS'}, H3 holds as non-inferiority only, H4 {'holds' if h4['holds'] else 'FAILS'}. Full tables: [`docs/RESULTS.md`](docs/RESULTS.md)."
)
rd = Path("README.md").read_text()
a, b = "<!-- headline:start -->", "<!-- headline:end -->"
if a in rd:
    rd = rd[: rd.index(a) + len(a)] + "\n" + head + "\n" + rd[rd.index(b) :]
    Path("README.md").write_text(rd)
print("wrote docs/RESULTS.md")
